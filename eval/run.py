"""Eval harness.

    python -m eval.run                  synthetic regression set (CI gate: add --gate)
    python -m eval.run --set verified   human-verified gold set from eval/gold/verified/verified.jsonl
    python -m eval.run --llm            same, with the configured live LLM writing review briefs

Every report says which data it ran on (`data`) and, with --llm, which provider/model.
"""
import base64
import json
import sys
import time
from pathlib import Path

from agent import graph as G
from agent import llm
from agent.graph import build
from eval.feedback_slice import summarize as feedback_slice

ROOT = Path(__file__).parent
GOLD = ROOT / "gold" / "cases.json"                  # synthetic, generated by make_seed.py
VERIFIED = ROOT / "gold" / "verified" / "verified.jsonl"


def _b64(rel: str | None) -> str | None:
    return base64.b64encode((VERIFIED.parent / rel).read_bytes()).decode() if rel else None


def load_cases(which: str) -> list[dict]:
    if which == "synthetic":
        return [{**c, "split": "all", "source": "synthetic"} for c in json.loads(GOLD.read_text())]
    if not VERIFIED.exists():
        sys.exit("no verified set yet: build it with `python -m eval.label` (see eval/gold/README.md)")
    out = []
    for line in VERIFIED.read_text().splitlines():
        r = json.loads(line)
        claim = {k: r.get(k) for k in ("id", "order_id", "customer_id", "text", "amount_inr", "days_since_delivery")}
        claim |= {"image_b64": _b64(r.get("photo")), "invoice_b64": _b64(r.get("invoice"))}
        out.append({"claim": {k: v for k, v in claim.items() if v is not None}, "expected": r["expected"],
                    "split": r["split"], "source": r["source"]})
    return out


def _pct(xs: list[float], q: float):
    xs = sorted(xs)
    return round(xs[int(q * (len(xs) - 1))], 1) if xs else None
BASELINE = ROOT / "baseline.json"


def run() -> dict:
    which = sys.argv[sys.argv.index("--set") + 1] if "--set" in sys.argv else "synthetic"
    info = {"provider": None, "model": None}
    if "--llm" in sys.argv:                       # real model, when ANTHROPIC_API_KEY is set
        model = llm.get_llm()
        if model is None:
            sys.exit("--llm needs ANTHROPIC_API_KEY (and langchain-anthropic)")
        G.set_reader(llm.Reader(model))
        info = llm.model_info()
    graph = build()
    cases = load_cases(which)
    correct, verified, lat, briefs, predictions, labels = 0, 0, [], [], [], []
    by_split: dict[str, list[int]] = {}
    for c in cases:
        t = time.perf_counter()
        out = graph.invoke({"claim": c["claim"]})
        lat.append((time.perf_counter() - t) * 1000)
        hit = out["decision"]["decision"] == c["expected"]
        correct += hit
        by_split.setdefault(c["split"], []).append(int(hit))
        predictions.append(out["decision"]["decision"])
        labels.append(c["expected"])
        verified += bool(out["verified"])
        if out.get("brief"):
            briefs.append(out["brief"])
    lat.sort()
    tab = ROOT.parent / "ml" / "artifacts" / "tabular_metrics.json"
    extra = json.loads(tab.read_text()) if tab.exists() else {}
    llm_lat = [b["latency_ms"] for b in briefs if b.get("llm_used") and "latency_ms" in b]
    return {**(extra if which == "synthetic" else {}),
        "data": "synthetic" if which == "synthetic" else "human_verified",
        "sources": {s: sum(c["source"] == s for c in cases) for s in {c["source"] for c in cases}},
        "n": len(cases),
        "accuracy_by_split": {k: {"n": len(v), "accuracy": round(sum(v) / len(v), 4)} for k, v in sorted(by_split.items())},
        "decision_accuracy": round(correct / len(cases), 4),
        "verification_rate": round(verified / len(cases), 4),
        "p95_ms": round(lat[int(0.95 * (len(lat) - 1))], 2),
        # share of cases the policy could not settle, i.e. the only ones that reach the LLM
        "llm_routed_rate": round(len(briefs) / len(cases), 4),
        "llm_used_rate": round(sum(b["llm_used"] for b in briefs) / len(cases), 4),
        "avg_cost_inr": round(sum(b["cost_inr"] for b in briefs) / len(cases), 4),
        "groundedness": (round(sum(g) / len(g), 4) if (g := [b["groundedness"] for b in briefs if b.get("groundedness") is not None]) else None),
        "llm": {**info, "calls": len(llm_lat), "errors": sum(1 for b in briefs if b.get("error")),
                "latency_p50_ms": _pct(llm_lat, 0.5), "latency_p95_ms": _pct(llm_lat, 0.95),
                "in_tokens": sum(b.get("in_tokens", 0) for b in briefs),
                "out_tokens": sum(b.get("out_tokens", 0) for b in briefs),
                "total_cost_inr": round(sum(b["cost_inr"] for b in briefs), 4)},
        "feedback_slice": feedback_slice(predictions, labels),
    }


def gate(m: dict) -> int:
    if not BASELINE.exists():
        print("no baseline; skipping gate")
        return 0
    b = json.loads(BASELINE.read_text())
    fails = []
    if m["decision_accuracy"] < b["decision_accuracy"]:
        fails.append("decision_accuracy regressed")
    if m["verification_rate"] < b["verification_rate"]:
        fails.append("verification_rate regressed")
    if m["p95_ms"] > b["p95_ms"] * 1.25 + 5:
        fails.append("p95_ms regressed")
    for f in fails:
        print("FAIL:", f)
    return 1 if fails else 0


if __name__ == "__main__":
    m = run()
    print(json.dumps(m, indent=2))
    name = "last_run.json" if m["data"] == "synthetic" and not m["llm"]["provider"] else \
        f"report_{m['data']}{'_llm' if m['llm']['provider'] else ''}.json"
    (ROOT / name).write_text(json.dumps(m, indent=2))
    if "--gate" in sys.argv:
        sys.exit(gate(m))
